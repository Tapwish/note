"""Регулярные выражения для всех этапов парсинга законов Majestic RP."""

import re

# --------------------------------------------------------------------------- #
# Статьи
# --------------------------------------------------------------------------- #

# "Статья 1", "Статья 1.", "Статья №1", "СТАТЬЯ 1", "Статья 1.1", "Статья 12.5"
# "ст. 1", "ст.1"
RE_ARTICLE = re.compile(
    r"^(?:Статья|Ст\.?)\s*№?\s*(\d+(?:\.\d+)?)\s*[.．]?\s*(.*)",
    re.IGNORECASE | re.UNICODE,
)

# --------------------------------------------------------------------------- #
# Части статьи
# --------------------------------------------------------------------------- #

# ч.1, ч. 1
RE_PART_CH = re.compile(
    r"^ч\.\s*(\d+(?:\.\d+)?)\s*[.．]?\s*(.*)",
    re.IGNORECASE | re.UNICODE,
)

# 1. (нумерованный список), 1) (нумерованный список со скобкой)
RE_PART_NUM = re.compile(
    r"^(\d+(?:\.\d+)?)\s*[.)]?\s*(.*)",
)

# а), б), в) (буквенные подпункты)
RE_PART_LETTER = re.compile(
    r"^([а-яА-Яa-zA-Z])\s*[).]\s*(.*)",
)

# I., II., III. (римские цифры)
RE_PART_ROMAN = re.compile(
    r"^([IVXLCDM]+)\s*[.．]\s*(.*)",
)

# Комбинированный: любой из вариантов части
RE_PART_ANY = re.compile(
    r"^(?:"
    r"ч\.\s*(\d+(?:\.\d+)?)"          # group(1): ч.1, ч. 1
    r"|"
    r"(\d+(?:\.\d+)?)\s*[.)]"          # group(2): 1., 1)
    r"|"
    r"([а-яА-Яa-zA-Z])\s*[).]"         # group(3): а), б)
    r"|"
    r"([IVXLCDM]+)\s*[.．]"             # group(4): I., II.
    r")"
    r"\s*(.*)",                         # group(5): текст части
    re.UNICODE,
)

# --------------------------------------------------------------------------- #
# Наказание
# --------------------------------------------------------------------------- #

# Маркеры начала наказания
RE_PENALTY_MARKER = re.compile(
    r"(?:"
    r"Наказание\s*[:–-]?"
    r"|Штраф\s*[:–-]?"
    r"|Санкция\s*[:–-]?"
    r"|Ответственность\s*[:–-]?"
    r"|Мера\s+наказания\s*[:–-]?"
    r")",
    re.IGNORECASE | re.UNICODE,
)

# --------------------------------------------------------------------------- #
# Wanted Stars
# --------------------------------------------------------------------------- #

# Конкретные числовые указания: "5 звезд", "3 звезды"
RE_WANTED_NUMERIC = re.compile(
    r"(\d+)\s*(?:звезд[аы]?|star[s]?)\b",
    re.IGNORECASE | re.UNICODE,
)

# Символьные звезды: ⭐⭐⭐, ★★★★★
RE_WANTED_STAR_SYMBOLS = re.compile(r"[⭐★☆✨]+")

# Ключевые слова wanted
RE_WANTED_KEYWORDS = re.compile(
    r"(?:"
    r"\bWanted\b"
    r"|\bРозыск\b"
    r"|\bЗвезды\b"
    r"|\bStars\b"
    r"|\bРазыскивается\b"
    r")",
    re.IGNORECASE | re.UNICODE,
)

# Поиск числа рядом с wanted-словами: "Wanted: 5", "Розыск 5 звезд"
RE_WANTED_VALUE = re.compile(
    r"(?:\bWanted\b|\bРозыск\b|\bЗвезды\b|\bStars\b)\s*[:–-]?\s*(\d+)",
    re.IGNORECASE | re.UNICODE,
)

# --------------------------------------------------------------------------- #
# Юрисдикция
# --------------------------------------------------------------------------- #

RE_JURISDICTION_MARKER = re.compile(
    r"(?:"
    r"Подследственность\s*[:–-]?"
    r"|Юрисдикция\s*[:–-]?"
    r"|\bJurisdiction\b\s*[:–-]?"
    r")",
    re.IGNORECASE | re.UNICODE,
)

# --------------------------------------------------------------------------- #
# Определение кодекса по названию темы
# --------------------------------------------------------------------------- #

CODEX_PATTERNS: dict[str, re.Pattern] = {
    "uk": re.compile(r"уголовн(?:ый|ого)\s+кодекс", re.IGNORECASE | re.UNICODE),
    "ak": re.compile(r"административн(?:ый|ого)\s+кодекс", re.IGNORECASE | re.UNICODE),
    "pk": re.compile(r"процессуальн(?:ый|ого)\s+кодекс", re.IGNORECASE | re.UNICODE),
    "dk": re.compile(r"дорожн(?:ый|ого)\s+кодекс", re.IGNORECASE | re.UNICODE),
}

# --------------------------------------------------------------------------- #
# Названия серверов на главной
# --------------------------------------------------------------------------- #

RE_SERVER_TITLE = re.compile(
    r"^Majestic\s*(?:РП|RP)\s*\|\s*(.+)$",
    re.IGNORECASE | re.UNICODE,
)
